        /* ============================================================
           TIMEZONE DISPLAY
        ============================================================ */

        function getTimezoneDisplay(timezone) {

            const zone = timezones.find(
                item => item.timezone === timezone
            );

            if (!zone) {
                return timezone;
            }

            return `${zone.city}, ${zone.country} — ${zone.abbreviation}`;
        }


        /* ============================================================
           SEARCHABLE TIMEZONE DROPDOWN
        ============================================================ */

        function setupTimezoneSearch(
            searchId,
            dropdownId,
            type
        ) {

            const searchInput =
                document.getElementById(searchId);

            const dropdown =
                document.getElementById(dropdownId);


            searchInput.addEventListener("focus", () => {

                renderTimezoneOptions(
                    "",
                    dropdown,
                    type
                );

                dropdown.classList.add("active");

            });


            searchInput.addEventListener("input", () => {

                renderTimezoneOptions(
                    searchInput.value,
                    dropdown,
                    type
                );

                dropdown.classList.add("active");

            });


            document.addEventListener("click", (event) => {

                if (
                    !searchInput.contains(event.target) &&
                    !dropdown.contains(event.target)
                ) {

                    dropdown.classList.remove("active");

                }

            });

        }


        /* ============================================================
           RENDER SEARCH RESULTS
        ============================================================ */

        function renderTimezoneOptions(
            searchText,
            dropdown,
            type
        ) {

            const query =
                searchText
                    .toLowerCase()
                    .trim();


            const results =
                timezones.filter(zone => {

                    const searchableText = [
                        zone.city,
                        zone.country,
                        zone.abbreviation,
                        zone.timezone,
                        zone.group
                    ]
                        .join(" ")
                        .toLowerCase();

                    return searchableText.includes(query);

                });


            dropdown.innerHTML = "";


            if (results.length === 0) {

                dropdown.innerHTML = `
            <div class="timezone-option">
                No timezone found
            </div>
        `;

                return;
            }


            let currentGroup = "";


            results.forEach(zone => {

                if (zone.group !== currentGroup) {

                    currentGroup = zone.group;

                    const groupTitle =
                        document.createElement("div");

                    groupTitle.className =
                        "timezone-group-title";

                    groupTitle.textContent =
                        zone.group;

                    dropdown.appendChild(groupTitle);

                }


                const option =
                    document.createElement("div");

                option.className =
                    "timezone-option";


                option.innerHTML = `
            <strong>
                ${getFlag(zone.country)}
                ${zone.city}, ${zone.country}
            </strong>

            <span>
                ${zone.abbreviation}
                &nbsp; • &nbsp;
                ${zone.timezone}
            </span>
        `;


                option.addEventListener("click", () => {

                    if (type === "from") {

                        fromTimezone =
                            zone.timezone;

                        document.getElementById(
                            "fromSearch"
                        ).value =
                            getTimezoneDisplay(
                                zone.timezone
                            );

                    } else {

                        toTimezone =
                            zone.timezone;

                        document.getElementById(
                            "toSearch"
                        ).value =
                            getTimezoneDisplay(
                                zone.timezone
                            );

                    }


                    dropdown.classList.remove("active");

                });


                dropdown.appendChild(option);

            });

        }


